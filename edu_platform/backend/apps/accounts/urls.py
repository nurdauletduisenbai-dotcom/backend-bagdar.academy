from django.urls import path

from .views import (
    ActiveSessionsView,
    ChangePasswordView,
    LoginView,
    LogoutAllView,
    LogoutView,
    PasswordResetConfirmView,
    PasswordResetRequestView,
    RefreshTokenView,
    RegisterByInviteView,
    RegisterView,
    ResendVerificationView,
    SessionDetailView,
    TwoFactorDisableView,
    TwoFactorEnableView,
    TwoFactorSetupView,
    UserProfileView,
    VerifyEmailView,
)

urlpatterns = [
    path('register/', RegisterView.as_view(), name='auth_register'),
    path('register-by-invite/', RegisterByInviteView.as_view(), name='auth_register_by_invite'),
    path('verify-email/', VerifyEmailView.as_view(), name='auth_verify_email'),
    path('verify-email/resend/', ResendVerificationView.as_view(), name='auth_verify_email_resend'),
    path('password-reset/', PasswordResetRequestView.as_view(), name='auth_password_reset'),
    path('password-reset/confirm/', PasswordResetConfirmView.as_view(), name='auth_password_reset_confirm'),
    path('login/', LoginView.as_view(), name='auth_login'),
    path('refresh/', RefreshTokenView.as_view(), name='auth_refresh'),
    path('logout/', LogoutView.as_view(), name='auth_logout'),
    path('logout-all/', LogoutAllView.as_view(), name='auth_logout_all'),
    path('change-password/', ChangePasswordView.as_view(), name='auth_change_password'),
    path('sessions/', ActiveSessionsView.as_view(), name='auth_sessions'),
    path('sessions/<int:session_id>/', SessionDetailView.as_view(), name='auth_session_detail'),
    path('2fa/setup/', TwoFactorSetupView.as_view(), name='auth_2fa_setup'),
    path('2fa/enable/', TwoFactorEnableView.as_view(), name='auth_2fa_enable'),
    path('2fa/disable/', TwoFactorDisableView.as_view(), name='auth_2fa_disable'),
    path('users/me/', UserProfileView.as_view(), name='user_me'),
]
